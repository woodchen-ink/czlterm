/** 从错误里取出码与原始说明。 */
export function parseError(e: unknown): { code: string; raw: string } {
  const raw = e instanceof Error ? e.message : String(e ?? "");
  const m = /^(\d{4})\s+([\s\S]*)$/.exec(raw.trim());
  return m ? { code: m[1], raw: m[2] } : { code: "", raw };
}

/** 给界面展示的错误文案, 带上错误码。 */
export function errorText(e: unknown): string {
  const { code, raw } = parseError(e);
  if (!code) return raw || "未知错误";
  const known = messages[code];
  // 文件操作类错误的原始说明里有 "not found" / "permission denied" 等关键信息, 一并带上。
  if (known) return `${known} (${code})`;
  return `${raw} (${code})`;
}

export function isLockedError(e: unknown): boolean {
  return parseError(e).code === "3001";
}
